using System;
using System.Collections.Immutable;
using System.Linq;
using System.Reflection;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using NetPrints.Analyzers.Tests.Infrastructure;
using NetPrints.Core;
using NetPrints.Graph;
using Xunit;

namespace NetPrints.Analyzers.Tests.Pins;

public class PinConventionGeneratorTests
{
    private static readonly string[] Steps = ["NodeKindPins", "NodeBasePins"];

    private const string Typed = """
        using NetPrints.Core;
        using NetPrints.Graph;

        namespace Sample;

        [NodeKind("sample.loop")]
        public sealed partial class LoopNode : Node
        {
            public LoopNode(NodeGraph graph) : base(graph)
            {
                DeclarePins();
            }

            public partial NodeInputExecPin ExecutionPin { get; }

            public partial NodeOutputExecPin LoopPin { get; }

            public partial NodeInputDataPin<int> InitialIndexPin { get; }

            public partial NodeOutputDataPin<int> IndexPin { get; }
        }
        """;

    private const string Override = """
        using NetPrints.Core;
        using NetPrints.Graph;

        namespace Sample;

        [NodeKind("sample.result")]
        public sealed partial class ResultNode : Node
        {
            public ResultNode(NodeGraph graph) : base(graph)
            {
                DeclarePins();
            }

            [Pin("Value", Role = PinRole.Result)]
            public partial NodeOutputDataPin<object> ResultPin { get; }
        }
        """;

    private const string Based = """
        using NetPrints.Core;
        using NetPrints.Graph;

        namespace Sample;

        [NodeBase]
        public abstract partial class ExecBase : Node
        {
            protected ExecBase(NodeGraph graph) : base(graph)
            {
            }

            public partial NodeInputExecPin ExecutionPin { get; }

            public partial NodeOutputExecPin ThenPin { get; }
        }

        [NodeKind("sample.branch")]
        public sealed partial class BranchNode : ExecBase
        {
            public BranchNode(NodeGraph graph) : base(graph)
            {
                DeclarePins();
            }

            public partial NodeInputDataPin<bool> ConditionPin { get; }

            public partial NodeOutputExecPin ElsePin { get; }
        }
        """;

    private const string Defaulted = """
        using System.ComponentModel;
        using NetPrints.Core;
        using NetPrints.Graph;

        namespace Sample;

        [NodeKind("sample.repeat")]
        public sealed partial class RepeatNode : Node
        {
            public RepeatNode(NodeGraph graph) : base(graph)
            {
                DeclarePins();
            }

            [DefaultValue(3)]
            public partial NodeInputDataPin<int> CountPin { get; }

            [DefaultValue("hi")]
            public partial NodeInputDataPin<string> TextPin { get; }
        }
        """;

    [Fact]
    public void TypedPinsAreDeclaredInOrderAndImplemented()
    {
        GeneratorRun run = AuthoringHarness.Run(Typed);

        Assert.Empty(run.Diagnostics);
        Assert.Equal(
            """
            // <auto-generated/>
            #nullable enable
            namespace Sample
            {
                [global::NetPrints.Graph.NodePinLayout("in.exec.Execution", "out.exec.Loop", "in.data.InitialIndex", "out.data.Index")]
                partial class LoopNode
                {
                    private void DeclarePins()
                    {
                        AddInputExecPin("Execution");
                        AddOutputExecPin("Loop");
                        InputDataPins.Add(new global::NetPrints.Graph.NodeInputDataPin<int>(this, "InitialIndex"));
                        OutputDataPins.Add(new global::NetPrints.Graph.NodeOutputDataPin<int>(this, "Index"));
                    }

                    public partial global::NetPrints.Graph.NodeInputExecPin ExecutionPin => InputExecPins[0];

                    public partial global::NetPrints.Graph.NodeOutputExecPin LoopPin => OutputExecPins[0];

                    public partial global::NetPrints.Graph.NodeInputDataPin<int> InitialIndexPin => (global::NetPrints.Graph.NodeInputDataPin<int>)InputDataPins[0];

                    public partial global::NetPrints.Graph.NodeOutputDataPin<int> IndexPin => (global::NetPrints.Graph.NodeOutputDataPin<int>)OutputDataPins[0];
                }
            }

            """,
            Normalize(run.Source("NodePins.Sample.LoopNode.g.cs")));
    }

    [Fact]
    public void ThePinAttributeOverridesTheKey()
    {
        GeneratorRun run = AuthoringHarness.Run(Override);

        Assert.Empty(run.Diagnostics);
        Assert.Equal(
            """
            // <auto-generated/>
            #nullable enable
            namespace Sample
            {
                [global::NetPrints.Graph.NodePinLayout("out.data.Value")]
                partial class ResultNode
                {
                    private void DeclarePins()
                    {
                        OutputDataPins.Add(new global::NetPrints.Graph.NodeOutputDataPin<object>(this, "Value"));
                    }

                    public partial global::NetPrints.Graph.NodeOutputDataPin<object> ResultPin => (global::NetPrints.Graph.NodeOutputDataPin<object>)OutputDataPins[0];
                }
            }

            """,
            Normalize(run.Source("NodePins.Sample.ResultNode.g.cs")));
    }

    [Fact]
    public void ADerivedKindContinuesAfterTheBasePins()
    {
        GeneratorRun run = AuthoringHarness.Run(Based);

        Assert.Empty(run.Diagnostics);
        Assert.Equal(
            """
            // <auto-generated/>
            #nullable enable
            namespace Sample
            {
                [global::NetPrints.Graph.NodePinLayout("in.exec.Execution", "out.exec.Then")]
                partial class ExecBase
                {
                    /// <summary>Declares the pins of this class.</summary>
                    protected void DeclarePins()
                    {
                        AddInputExecPin("Execution");
                        AddOutputExecPin("Then");
                    }

                    public partial global::NetPrints.Graph.NodeInputExecPin ExecutionPin => InputExecPins[0];

                    public partial global::NetPrints.Graph.NodeOutputExecPin ThenPin => OutputExecPins[0];
                }
            }

            """,
            Normalize(run.Source("NodePins.Sample.ExecBase.g.cs")));
        Assert.Equal(
            """
            // <auto-generated/>
            #nullable enable
            namespace Sample
            {
                [global::NetPrints.Graph.NodePinLayout("in.data.Condition", "out.exec.Else")]
                partial class BranchNode
                {
                    private new void DeclarePins()
                    {
                        base.DeclarePins();
                        InputDataPins.Add(new global::NetPrints.Graph.NodeInputDataPin<bool>(this, "Condition"));
                        AddOutputExecPin("Else");
                    }

                    public partial global::NetPrints.Graph.NodeInputDataPin<bool> ConditionPin => (global::NetPrints.Graph.NodeInputDataPin<bool>)InputDataPins[0];

                    public partial global::NetPrints.Graph.NodeOutputExecPin ElsePin => OutputExecPins[1];
                }
            }

            """,
            Normalize(run.Source("NodePins.Sample.BranchNode.g.cs")));
    }

    [Fact]
    public void ABclDefaultValueSetsTheUnconnectedValue()
    {
        GeneratorRun run = AuthoringHarness.Run(Defaulted);

        Assert.Empty(run.Diagnostics);
        Assert.Equal(
            """
            // <auto-generated/>
            #nullable enable
            namespace Sample
            {
                [global::NetPrints.Graph.NodePinLayout("in.data.Count", "in.data.Text")]
                partial class RepeatNode
                {
                    private void DeclarePins()
                    {
                        InputDataPins.Add(new global::NetPrints.Graph.NodeInputDataPin<int>(this, "Count") { UnconnectedValue = (int)3 });
                        InputDataPins.Add(new global::NetPrints.Graph.NodeInputDataPin<string>(this, "Text") { UnconnectedValue = "hi" });
                    }

                    public partial global::NetPrints.Graph.NodeInputDataPin<int> CountPin => (global::NetPrints.Graph.NodeInputDataPin<int>)InputDataPins[0];

                    public partial global::NetPrints.Graph.NodeInputDataPin<string> TextPin => (global::NetPrints.Graph.NodeInputDataPin<string>)InputDataPins[1];
                }
            }

            """,
            Normalize(run.Source("NodePins.Sample.RepeatNode.g.cs")));
    }

    [Fact]
    public void TheGeneratedCodeCompilesAndDeclaresTheSamePins()
    {
        GeneratorRun run = AuthoringHarness.Run(Typed, Based, Defaulted);

        Assert.Empty(run.CompileErrors());
        Assembly assembly = GeneratorHarness.EmitAndLoad(run.Output);

        Node loop = Create(assembly, "Sample.LoopNode");
        Assert.Equal(["Execution"], loop.InputExecPins.Select(pin => pin.Name));
        Assert.Equal(["Loop"], loop.OutputExecPins.Select(pin => pin.Name));
        Assert.Equal(["InitialIndex"], loop.InputDataPins.Select(pin => pin.Name));
        Assert.Same(loop.OutputDataPins[0], loop.GetType().GetProperty("IndexPin")?.GetValue(loop));

        Node branch = Create(assembly, "Sample.BranchNode");
        Assert.Equal(["Execution"], branch.InputExecPins.Select(pin => pin.Name));
        Assert.Equal(["Then", "Else"], branch.OutputExecPins.Select(pin => pin.Name));
        Assert.Same(branch.OutputExecPins[1], branch.GetType().GetProperty("ElsePin")?.GetValue(branch));
        Assert.Same(branch.OutputExecPins[0], branch.GetType().GetProperty("ThenPin")?.GetValue(branch));

        Node repeat = Create(assembly, "Sample.RepeatNode");
        Assert.Equal(3, repeat.InputDataPins[0].UnconnectedValue);
        Assert.Equal("hi", repeat.InputDataPins[1].UnconnectedValue);
    }

    [Fact]
    public void ChangingAnUnrelatedFileLeavesEveryStepCached()
    {
        CSharpCompilation compilation = AuthoringHarness.Compile(Typed, "namespace Other { public class Unrelated { } }");
        GeneratorDriver driver = AuthoringHarness.CreateDriver(trackSteps: true).RunGenerators(compilation, TestContext.Current.CancellationToken);
        Assert.NotEmpty(StepReasons(driver));
        Assert.All(StepReasons(driver), reason => Assert.Equal(IncrementalStepRunReason.New, reason));

        SyntaxTree changed = CSharpSyntaxTree.ParseText("namespace Other { public class Unrelated { public int X; } }", path: "Sample1.cs", cancellationToken: TestContext.Current.CancellationToken);
        driver = driver.RunGenerators(compilation.ReplaceSyntaxTree(compilation.SyntaxTrees.Last(), changed), TestContext.Current.CancellationToken);

        Assert.All(StepReasons(driver), reason => Assert.True(reason is IncrementalStepRunReason.Cached or IncrementalStepRunReason.Unchanged, reason.ToString()));
    }

    [Fact]
    public void AddingAPinChangesTheGeneratedSource()
    {
        CSharpCompilation compilation = AuthoringHarness.Compile(Typed);
        GeneratorDriver driver = AuthoringHarness.CreateDriver(trackSteps: true).RunGenerators(compilation, TestContext.Current.CancellationToken);

        SyntaxTree changed = CSharpSyntaxTree.ParseText(
            Typed.Replace("public partial NodeOutputDataPin<int> IndexPin { get; }", "public partial NodeOutputDataPin<int> IndexPin { get; }\n\n    public partial NodeOutputDataPin<int> TotalPin { get; }", StringComparison.Ordinal),
            path: "Sample0.cs",
            cancellationToken: TestContext.Current.CancellationToken);
        driver = driver.RunGenerators(compilation.ReplaceSyntaxTree(compilation.SyntaxTrees.First(), changed), TestContext.Current.CancellationToken);

        Assert.Contains(StepReasons(driver), reason => reason == IncrementalStepRunReason.Modified);
        Assert.Contains("\"Total\"", GeneratorHarness.Sources(driver)["NodePins.Sample.LoopNode.g.cs"], StringComparison.Ordinal);
    }

    private static Node Create(Assembly assembly, string typeName) =>
        Assert.IsAssignableFrom<Node>(Activator.CreateInstance(assembly.GetType(typeName) ?? throw new InvalidOperationException(typeName), new MethodGraph("M")));

    private static string Normalize(string text) => text.Replace("\r\n", "\n", StringComparison.Ordinal);

    private static ImmutableArray<IncrementalStepRunReason> StepReasons(GeneratorDriver driver) =>
    [
        .. driver.GetRunResult().Results
            .SelectMany(result => Steps.Where(result.TrackedSteps.ContainsKey).SelectMany(step => result.TrackedSteps[step]))
            .SelectMany(step => step.Outputs)
            .Select(output => output.Reason),
    ];
}

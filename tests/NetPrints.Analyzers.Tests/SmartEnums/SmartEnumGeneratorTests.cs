using System;
using System.Collections;
using System.Collections.Immutable;
using System.Linq;
using System.Reflection;
using System.Runtime.CompilerServices;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using NetPrints.Analyzers.Tests.Infrastructure;
using Xunit;

namespace NetPrints.Analyzers.Tests.SmartEnums;

public class SmartEnumGeneratorTests
{
    private const string Hint = "SmartEnum.Sample.Color.g.cs";

    private const string SmartEnumsStep = "SmartEnums";

    private const string Sample = """
        using System.Collections.Generic;
        using System.Linq;
        using NetPrints.SmartEnums;

        namespace Sample;

        [SmartEnum]
        public abstract partial class Color
        {
            public static readonly Color Red = new RedColor();

            public static readonly Color Green = new GreenColor();

            private static readonly Dictionary<string, Color> ByName = All.ToDictionary(color => color.Id.ToString());

            public abstract ColorId Id { get; }

            public virtual string Glyph => Id.ToString();

            public static Color Find(string name) => ByName[name];

            private sealed class RedColor : Color
            {
                public override ColorId Id => ColorId.Red;

                public override string Glyph => "R";
            }

            private sealed class GreenColor : Color
            {
                public override ColorId Id => ColorId.Green;
            }
        }
        """;

    [Fact]
    public void OnlyTheCompanionIdEnumAndTheAllListAreGenerated()
    {
        GeneratorRun run = GeneratorHarness.Run(Sample);

        Assert.Equal(
            """
            // <auto-generated/>
            #nullable enable
            namespace Sample
            {
                /// <summary>The members of <see cref="Color"/>, for attributes and stored ids.</summary>
                public enum ColorId
                {
                    /// <summary>The <c>Red</c> member.</summary>
                    Red,
                    /// <summary>The <c>Green</c> member.</summary>
                    Green,
                }

                partial class Color
                {
                    private static global::System.Collections.Generic.IReadOnlyList<global::Sample.Color>? allMembers;

                    /// <summary>Gets every member, in declaration order.</summary>
                    public static global::System.Collections.Generic.IReadOnlyList<global::Sample.Color> All => allMembers ??= global::System.Array.AsReadOnly(new global::Sample.Color[] { Red, Green });
                }
            }

            """.Replace("\r\n", "\n", StringComparison.Ordinal),
            run.Source(Hint));
    }

    [Fact]
    public void TheOutputCompilesWithoutErrorsOrDiagnostics()
    {
        GeneratorRun run = GeneratorHarness.Run(Sample);

        Assert.Empty(run.CompileErrors());
        Assert.Empty(run.Diagnostics);
    }

    [Fact]
    public void NothingIsEmittedWithoutTheAttribute()
    {
        GeneratorRun run = GeneratorHarness.Run("namespace Sample { public abstract partial class Color { } }");

        Assert.DoesNotContain(Hint, run.Sources.Keys);
    }

    [Fact]
    public void TouchingTheStaticConstructorDoesNotThrowAndTheIdsMapOneToOne()
    {
        Assembly assembly = GeneratorHarness.EmitAndLoad(GeneratorHarness.Run(Sample).Output);
        Type color = assembly.GetType("Sample.Color") ?? throw new InvalidOperationException("Sample.Color is missing.");
        Type ids = assembly.GetType("Sample.ColorId") ?? throw new InvalidOperationException("Sample.ColorId is missing.");

        RuntimeHelpers.RunClassConstructor(color.TypeHandle);

        object[] all = [.. ((IEnumerable)(color.GetProperty("All")?.GetValue(null) ?? Array.Empty<object>())).Cast<object>()];
        string[] memberIds = [.. all.Select(member => member.GetType().GetProperty("Id")?.GetValue(member)?.ToString() ?? string.Empty)];
        Assert.Equal(["Red", "Green"], memberIds);
        Assert.Equal(["Red", "Green"], Enum.GetNames(ids));
        object red = color.GetMethod("Find")?.Invoke(null, ["Red"]) ?? throw new InvalidOperationException("Find returned nothing.");
        Assert.Equal("R", red.GetType().GetProperty("Glyph")?.GetValue(red));
    }

    [Fact]
    public void AnUnrelatedChangeKeepsTheSmartEnumStepCached()
    {
        CSharpCompilation compilation = GeneratorHarness.Compile(Sample, "namespace Other { public class Unrelated { } }");
        GeneratorDriver driver = GeneratorHarness.CreateDriver(trackSteps: true).RunGenerators(compilation, TestContext.Current.CancellationToken);
        Assert.All(StepReasons(driver), reason => Assert.Equal(IncrementalStepRunReason.New, reason));

        SyntaxTree changed = CSharpSyntaxTree.ParseText("namespace Other { public class Unrelated { public int X; } }", path: "Sample1.cs", cancellationToken: TestContext.Current.CancellationToken);
        driver = driver.RunGenerators(compilation.ReplaceSyntaxTree(compilation.SyntaxTrees.Last(), changed), TestContext.Current.CancellationToken);

        Assert.All(StepReasons(driver), reason => Assert.True(reason is IncrementalStepRunReason.Cached or IncrementalStepRunReason.Unchanged, reason.ToString()));
    }

    [Fact]
    public void AddingAMemberChangesTheGeneratedEnum()
    {
        CSharpCompilation compilation = GeneratorHarness.Compile(Sample);
        GeneratorDriver driver = GeneratorHarness.CreateDriver(trackSteps: true).RunGenerators(compilation, TestContext.Current.CancellationToken);

        SyntaxTree changed = CSharpSyntaxTree.ParseText(
            Sample.Replace("public static readonly Color Green = new GreenColor();", "public static readonly Color Green = new GreenColor();\n    public static readonly Color Blue = new GreenColor();", StringComparison.Ordinal),
            path: "Sample0.cs",
            cancellationToken: TestContext.Current.CancellationToken);
        driver = driver.RunGenerators(compilation.ReplaceSyntaxTree(compilation.SyntaxTrees.First(), changed), TestContext.Current.CancellationToken);

        Assert.Contains(StepReasons(driver), reason => reason == IncrementalStepRunReason.Modified);
        Assert.Contains("Blue,", GeneratorHarness.Sources(driver)[Hint], StringComparison.Ordinal);
    }

    private static ImmutableArray<IncrementalStepRunReason> StepReasons(GeneratorDriver driver) =>
    [
        .. driver.GetRunResult().Results
            .Where(result => result.TrackedSteps.ContainsKey(SmartEnumsStep))
            .SelectMany(result => result.TrackedSteps[SmartEnumsStep])
            .SelectMany(step => step.Outputs)
            .Select(output => output.Reason),
    ];
}

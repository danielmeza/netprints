using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace NetPrints.Authoring.Pins;

/// <summary>
/// Implements the <c>partial</c> pin properties of <c>[NodeKind]</c> and <c>[NodeBase]</c> node classes and emits their
/// <c>DeclarePins()</c> method: a pin's key is its property name without the <c>Pin</c> suffix unless <c>[Pin("…")]</c>
/// overrides it, and a derived class continues after the pins its bases declare.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class PinConventionGenerator : IIncrementalGenerator
{
    internal const string NodeKindStep = "NodeKindPins";

    internal const string NodeBaseStep = "NodeBasePins";

    private const string NodeKindMetadataName = "NetPrints.Graph.NodeKindAttribute";

    private const string NodeBaseMetadataName = "NetPrints.Graph.NodeBaseAttribute";

    private const string GraphPrefix = "global::NetPrints.Graph.";

    private const string Indent = "    ";

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<PinSetModel?> kinds = context.SyntaxProvider
            .ForAttributeWithMetadataName(NodeKindMetadataName, static (node, _) => node is ClassDeclarationSyntax, static (attribute, token) => PinReader.ReadKind(attribute, token))
            .WithTrackingName(NodeKindStep);

        IncrementalValuesProvider<PinSetModel?> bases = context.SyntaxProvider
            .ForAttributeWithMetadataName(NodeBaseMetadataName, static (node, _) => node is ClassDeclarationSyntax, static (attribute, token) => PinReader.ReadBase(attribute, token))
            .WithTrackingName(NodeBaseStep);

        context.RegisterSourceOutput(kinds, static (output, model) => Emit(output, model));
        context.RegisterSourceOutput(bases, static (output, model) => Emit(output, model));
    }

    private static void Emit(SourceProductionContext output, PinSetModel? model)
    {
        if (model is null)
        {
            return;
        }

        string qualified = (model.Namespace.Length == 0 ? string.Empty : model.Namespace + ".") + string.Join(".", model.Containers.Items) + (model.Containers.Length == 0 ? string.Empty : ".") + model.Name;
        output.AddSource("NodePins." + qualified + ".g.cs", SourceText.From(Source(model), Encoding.UTF8));
    }

    private static string Source(PinSetModel model)
    {
        StringBuilder text = new("// <auto-generated/>\n#nullable enable\n");
        int depth = 0;
        if (model.Namespace.Length > 0)
        {
            text.Append("namespace ").Append(model.Namespace).Append("\n{\n");
            depth++;
        }

        foreach (string container in model.Containers)
        {
            Line(text, depth, "partial class " + container);
            Line(text, depth, "{");
            depth++;
        }

        Line(text, depth, "[" + GraphPrefix + "NodePinLayout(" + string.Join(", ", Layout(model)) + ")]");
        Line(text, depth, "partial class " + model.Name);
        Line(text, depth, "{");
        depth++;
        Declare(text, model, depth);
        PinCounts running = model.Offsets;
        foreach (PinModel pin in model.Pins)
        {
            text.Append('\n');
            Line(text, depth, pin.Accessibility + " partial " + pin.TypeName + " " + pin.Name + " => " + Access(pin, running.Of(pin.Kind)) + ";");
            running = running.Add(pin.Kind);
        }

        for (; depth > 0; depth--)
        {
            Line(text, depth - 1, "}");
        }

        return text.ToString();
    }

    private static void Declare(StringBuilder text, PinSetModel model, int depth)
    {
        Line(text, depth, (model.IsSealed ? "private" : "protected") + (model.HasBase ? " new" : string.Empty) + " void DeclarePins()");
        Line(text, depth, "{");
        if (model.HasBase)
        {
            Line(text, depth + 1, "base.DeclarePins();");
        }

        foreach (PinModel pin in model.Pins)
        {
            Line(text, depth + 1, Declaration(pin));
        }

        Line(text, depth, "}");
    }

    private static string Declaration(PinModel pin)
    {
        string member = pin.Member.Length == 0 ? string.Empty : ", " + pin.Member;
        string initializer = pin.DefaultExpression.Length == 0 ? string.Empty : " { UnconnectedValue = " + pin.DefaultExpression + " }";
        string key = Quote(pin.Key);
        switch (pin.Kind)
        {
            case PinKind.InputExec:
                return "AddInputExecPin(" + key + ");";
            case PinKind.OutputExec:
                return "AddOutputExecPin(" + key + ");";
            case PinKind.InputType:
                return "AddInputTypePin(" + key + ");";
            case PinKind.OutputType:
                return "AddOutputTypePin(" + key + member + ");";
            case PinKind.InputData:
                return "InputDataPins.Add(new " + pin.TypeName + "(this, " + key + member + ")" + initializer + ");";
            default:
                return "OutputDataPins.Add(new " + pin.TypeName + "(this, " + key + member + "));";
        }
    }

    private static string Access(PinModel pin, int index)
    {
        string slot = index.ToString(System.Globalization.CultureInfo.InvariantCulture);
        switch (pin.Kind)
        {
            case PinKind.InputExec:
                return "InputExecPins[" + slot + "]";
            case PinKind.OutputExec:
                return "OutputExecPins[" + slot + "]";
            case PinKind.InputType:
                return "InputTypePins[" + slot + "]";
            case PinKind.OutputType:
                return "OutputTypePins[" + slot + "]";
            case PinKind.InputData:
                return "(" + pin.TypeName + ")InputDataPins[" + slot + "]";
            default:
                return "(" + pin.TypeName + ")OutputDataPins[" + slot + "]";
        }
    }

    private static System.Collections.Generic.IEnumerable<string> Layout(PinSetModel model)
    {
        foreach (PinModel pin in model.Pins)
        {
            string direction = pin.Kind is PinKind.InputExec or PinKind.InputData or PinKind.InputType ? "in" : "out";
            string kind = pin.Kind is PinKind.InputExec or PinKind.OutputExec ? "exec" : pin.Kind is PinKind.InputType or PinKind.OutputType ? "type" : "data";
            yield return Quote(direction + "." + kind + "." + pin.Key);
        }
    }

    private static string Quote(string value) => SymbolDisplay.FormatLiteral(value, quote: true);

    private static void Line(StringBuilder text, int depth, string line)
    {
        for (int level = 0; level < depth; level++)
        {
            text.Append(Indent);
        }

        text.Append(line).Append('\n');
    }
}

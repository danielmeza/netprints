using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using NetPrints.RepoAnalyzers.Composition;

namespace NetPrints.RepoAnalyzers.SmartEnums;

/// <summary>
/// Emits what a smart enum would otherwise list three times (ADR-0034): the companion <c>{Name}Id</c> enum and the <c>All</c>
/// list, both read from the <c>static readonly</c> member fields of a <c>[SmartEnum]</c> abstract partial class. The lookup,
/// the aliases and the per-member behaviour stay hand-written.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class SmartEnumGenerator : IIncrementalGenerator
{
    internal const string SmartEnumsStep = "SmartEnums";

    private const string AttributeHintName = "NetPrintsSmartEnums.Attributes.g.cs";

    private const string AttributeMetadataName = "NetPrints.SmartEnums.SmartEnumAttribute";

    private const string Attribute = @"// <auto-generated/>
#nullable enable
namespace NetPrints.SmartEnums
{
    [global::Microsoft.CodeAnalysis.Embedded]
    [global::System.AttributeUsage(global::System.AttributeTargets.Class, Inherited = false)]
    internal sealed class SmartEnumAttribute : global::System.Attribute
    {
    }
}
";

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static output => output.AddSource(AttributeHintName, SourceText.From(Attribute, Encoding.UTF8)));

        IncrementalValuesProvider<SmartEnumModel> enums = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                AttributeMetadataName,
                static (node, _) => node is ClassDeclarationSyntax,
                static (attribute, token) => SmartEnumReader.Read(attribute, token))
            .WithTrackingName(SmartEnumsStep);

        context.RegisterSourceOutput(enums, static (output, model) => Emit(output, model));
    }

    private static void Emit(SourceProductionContext output, SmartEnumModel model)
    {
        foreach (DiagnosticModel diagnostic in model.Diagnostics)
        {
            DiagnosticDescriptor descriptor = diagnostic.Id == SmartEnumDiagnosticCodes.Shape ? SmartEnumDiagnosticCodes.ShapeRule : SmartEnumDiagnosticCodes.MemberRule;
            output.ReportDiagnostic(Diagnostic.Create(descriptor, diagnostic.Location.ToLocation(), diagnostic.First, diagnostic.Second));
        }

        if (model.Members.Length == 0)
        {
            return;
        }

        string hint = "SmartEnum." + (model.Namespace.Length == 0 ? string.Empty : model.Namespace + ".") + model.Name + ".g.cs";
        output.AddSource(hint, SourceText.From(Source(model), Encoding.UTF8));
    }

    private static string Source(SmartEnumModel model)
    {
        string indent = model.Namespace.Length == 0 ? string.Empty : "    ";
        string type = (model.Namespace.Length == 0 ? "global::" : "global::" + model.Namespace + ".") + model.Name;
        StringBuilder text = new("// <auto-generated/>\n#nullable enable\n");
        if (model.Namespace.Length > 0)
        {
            text.Append("namespace ").Append(model.Namespace).Append("\n{\n");
        }

        text.Append(indent).Append("/// <summary>The members of <see cref=\"").Append(model.Name).Append("\"/>, for attributes and stored ids.</summary>\n");
        text.Append(indent).Append(model.Accessibility).Append(" enum ").Append(model.Name).Append("Id\n").Append(indent).Append("{\n");
        foreach (string member in model.Members)
        {
            text.Append(indent).Append("    /// <summary>The <c>").Append(member).Append("</c> member.</summary>\n");
            text.Append(indent).Append("    ").Append(member).Append(",\n");
        }

        text.Append(indent).Append("}\n\n");
        text.Append(indent).Append("partial class ").Append(model.Name).Append('\n').Append(indent).Append("{\n");
        text.Append(indent).Append("    private static global::System.Collections.Generic.IReadOnlyList<").Append(type).Append(">? allMembers;\n\n");
        text.Append(indent).Append("    /// <summary>Gets every member, in declaration order.</summary>\n");
        text.Append(indent).Append("    public static global::System.Collections.Generic.IReadOnlyList<").Append(type).Append("> All => allMembers ??= global::System.Array.AsReadOnly(new ").Append(type).Append("[] { ");
        text.Append(string.Join(", ", model.Members)).Append(" });\n");
        text.Append(indent).Append("}\n");
        if (model.Namespace.Length > 0)
        {
            text.Append("}\n");
        }

        return text.ToString();
    }
}

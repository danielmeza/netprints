using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using NetPrints.Roslyn;

namespace NetPrints.RepoAnalyzers.Composition;

/// <summary>Writes the generated registration class and the scope factory implementations.</summary>
internal static class RegistrationEmitter
{
    /// <summary>The hint name of the registration class.</summary>
    public const string RegistrationHintName = "AddEditorServices.g.cs";

    private const string Header = "// <auto-generated/>\n#nullable enable\nusing global::Microsoft.Extensions.DependencyInjection;\n\n";

    private const string ServiceCollection = "global::Microsoft.Extensions.DependencyInjection.IServiceCollection";

    private const string LoggerFactory = "global::Microsoft.Extensions.Logging.ILoggerFactory";

    private const string LoggerFactoryExtensions = "global::Microsoft.Extensions.Logging.LoggerFactoryExtensions";

    private const string ProviderName = "sp";

    private const string FactoryProviderName = "services";

    /// <summary>Writes the <c>AddEditorServices</c> extension method.</summary>
    /// <param name="registrations">Every registration of the compilation.</param>
    /// <returns>The source, or null when nothing is registered.</returns>
    public static string? Registrations(IReadOnlyList<Registration> registrations)
    {
        Registration[] valid = [.. registrations.Where(registration => registration.Creation is not null)];
        if (valid.Length == 0)
        {
            return null;
        }

        HashSet<string> registered = [.. valid.Select(registration => registration.Service)];
        List<(Registration Registration, Registration? Owner)> lines = [];
        foreach (IReadOnlyList<Registration> group in RegistrationRules.ByImplementation(valid))
        {
            bool shared = group.Count > 1 && RegistrationRules.SharedProblem(group) is null;
            if (group.Count > 1 && !shared)
            {
                continue;
            }

            lines.Add((group[0], null));
            lines.AddRange(group.Skip(1).Select(other => (other, (Registration?)group[0])));
        }

        StringBuilder text = new(Header);
        text.Append("namespace ").Append(CompositionSources.Namespace).Append("\n{\n");
        text.Append("    internal static class GeneratedServiceRegistration\n    {\n");
        text.Append("        internal static ").Append(ServiceCollection).Append(" AddEditorServices(this ").Append(ServiceCollection).Append(" services)\n        {\n");
        foreach ((Registration registration, Registration? owner) in lines.OrderBy(line => line.Registration.Service, StringComparer.Ordinal).ThenBy(line => line.Registration.Implementation, StringComparer.Ordinal).ThenBy(line => line.Registration.Location.Span.Start))
        {
            string method = registration.Lifetime == RegistrationLifetime.Singleton ? "AddSingleton" : "AddScoped";
            string body = owner is null && registration.Creation is not null
                ? Expression(registration.Creation, ProviderName, registered, null)
                : "(" + registration.Service + ")" + Resolve(ProviderName, owner?.Service ?? string.Empty);
            text.Append("            services.").Append(method).Append('<').Append(registration.Service).Append(">(static ").Append(ProviderName).Append(" => ").Append(body).Append(");\n");
        }

        text.Append("            return services;\n        }\n    }\n}\n");
        return text.ToString();
    }

    /// <summary>Gets the hint name of a scope factory.</summary>
    /// <param name="factory">The scope factory.</param>
    /// <returns>The hint name.</returns>
    public static string ScopeFactoryHintName(ScopeFactoryModel factory) =>
        "ScopeFactory." + (factory.Namespace.Length == 0 ? string.Empty : factory.Namespace + ".") + factory.Name + ".g.cs";

    /// <summary>Writes the <c>Create</c> methods of a scope factory.</summary>
    /// <param name="factory">The scope factory.</param>
    /// <param name="registrations">Every registration of the compilation.</param>
    /// <param name="unresolved">Receives the methods whose return type is neither registered nor constructible.</param>
    /// <returns>The source, or null when no method could be implemented.</returns>
    public static string? ScopeFactory(ScopeFactoryModel factory, IReadOnlyList<Registration> registrations, List<FactoryMethod> unresolved)
    {
        HashSet<string> registered = [.. registrations.Where(registration => registration.Creation is not null).Select(registration => registration.Service)];
        string indent = factory.Namespace.Length == 0 ? string.Empty : "    ";
        List<string> methods = [];
        foreach (FactoryMethod method in factory.Methods)
        {
            Creation? creation = registrations.FirstOrDefault(registration => registration.Creation is not null && registration.Service == method.ReturnType)?.Creation ?? method.ReturnCreation;
            if (creation is null)
            {
                unresolved.Add(method);
                continue;
            }

            string parameters = string.Join(", ", method.Parameters.Select(parameter => parameter.Type + " " + parameter.Name));
            string call = Expression(creation, FactoryProviderName, registered, new ParameterBinder(method.Parameters));
            methods.Add(indent + "    " + method.Modifiers + " partial " + method.ReturnType + " " + method.Name + "(" + parameters + ")\n" + indent + "    {\n" + indent + "        return " + call + ";\n" + indent + "    }\n");
        }

        if (methods.Count == 0)
        {
            return null;
        }

        StringBuilder text = new(Header);
        if (factory.Namespace.Length > 0)
        {
            text.Append("namespace ").Append(factory.Namespace).Append("\n{\n");
        }

        text.Append(indent).Append("partial class ").Append(factory.Name).Append('\n').Append(indent).Append("{\n");
        text.Append(string.Join("\n", methods));
        text.Append(indent).Append("}\n");
        if (factory.Namespace.Length > 0)
        {
            text.Append("}\n");
        }

        return text.ToString();
    }

    private static string Expression(Creation creation, string provider, HashSet<string> registered, ParameterBinder? binder)
    {
        string arguments = string.Join(", ", creation.Arguments.Select(dependency => Argument(dependency, provider, registered, binder)));
        return creation.Factory.Length == 0
            ? "new " + creation.Type + "(" + arguments + ")"
            : creation.Type + "." + creation.Factory + "(" + arguments + ")";
    }

    private static string Argument(Dependency dependency, string provider, HashSet<string> registered, ParameterBinder? binder)
    {
        switch (dependency.Kind)
        {
            case DependencyKind.Provider:
                return provider;
            case DependencyKind.Enumerable:
                return provider + ".GetServices<" + dependency.Type + ">()";
            case DependencyKind.Logger:
                return LoggerFactoryExtensions + ".CreateLogger<" + dependency.Type + ">(" + Resolve(provider, LoggerFactory) + ")";
            case DependencyKind.CategoryLogger:
                return Resolve(provider, LoggerFactory) + ".CreateLogger(\"" + dependency.Detail + "\")";
            case DependencyKind.Optional when !registered.Contains(dependency.Type):
                return binder?.Take(dependency.Type) ?? dependency.Detail;
            default:
                return binder?.Take(dependency.Type) ?? Resolve(provider, dependency.Type);
        }
    }

    private static string Resolve(string provider, string type) => provider + ".GetRequiredService<" + type + ">()";

    private sealed class ParameterBinder(EquatableArray<MethodParameter> parameters)
    {
        private readonly HashSet<int> used = [];

        public string? Take(string type)
        {
            int index = 0;
            foreach (MethodParameter parameter in parameters)
            {
                if (parameter.Type == type && used.Add(index))
                {
                    return parameter.Name;
                }

                index++;
            }

            return null;
        }
    }
}
